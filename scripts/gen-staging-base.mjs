// One-off remediation helper: reconstruct the production base schema as DDL
// so an empty staging project can be seeded before the hardening chain runs.
// Reads only catalog metadata through `supabase db query --linked` JSON
// output. Never selects or emits table data.
//
// Output sections (each introduced by a "-- SECTION: <name>" marker):
//   TABLES -> CONSTRAINTS -> INDEXES -> FUNCTIONS -> TRIGGERS -> POLICIES -> GRANTS
// Apply in that order; RLS helper functions must exist before POLICIES.
import { execFileSync } from "node:child_process"
import { writeFileSync } from "node:fs"

const CATALOG_SQL = `
select
  (select coalesce(json_agg(row_to_json(x)), '[]'::json) from (
    select c.relname as table_name, c.relrowsecurity as rls
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relkind = 'r'
  ) x) as tables,
  (select coalesce(json_agg(row_to_json(x) order by x.tbl, x.attnum), '[]'::json) from (
    select c.relname as tbl, a.attname as col, format_type(a.atttypid, a.atttypmod) as typ,
      a.attnotnull as notnull, pg_get_expr(d.adbin, d.adrelid) as deflt, a.attnum,
      a.attidentity as ident
    from pg_attribute a
    join pg_class c on c.oid = a.attrelid
    join pg_namespace n on n.oid = c.relnamespace
    left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
    where n.nspname = 'public' and c.relkind = 'r' and a.attnum > 0 and not a.attisdropped
  ) x) as columns,
  (select coalesce(json_agg(row_to_json(x)), '[]'::json) from (
    select conrelid::regclass::text as tbl, conname, contype, pg_get_constraintdef(oid) as def
    from pg_constraint where connamespace = 'public'::regnamespace
  ) x) as constraints,
  (select coalesce(json_agg(row_to_json(x)), '[]'::json) from (
    select indexname, indexdef from pg_indexes where schemaname = 'public'
  ) x) as indexes,
  (select coalesce(json_agg(row_to_json(x)), '[]'::json) from (
    select n.nspname as schema_name, p.proname, pg_get_functiondef(p.oid) as def
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname not in ('pg_catalog', 'information_schema', 'auth', 'storage', 'realtime', 'extensions', 'vault', 'supabase_functions', 'supabase_migrations', 'pgsodium', 'pgsodium_masks', 'net', 'pgtle', 'cron', 'graphql', 'graphql_public', 'pgbouncer', 'pgsodium', 'toml')
  ) x) as functions,
  (select coalesce(json_agg(row_to_json(x)), '[]'::json) from (
    select t.tgname, pg_get_triggerdef(t.oid) as def
    from pg_trigger t
    join pg_class c on c.oid = t.tgrelid
    join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and not t.tgisinternal
  ) x) as triggers,
  (select coalesce(json_agg(row_to_json(x)), '[]'::json) from (
    select tablename, policyname, permissive, roles, cmd, qual, with_check
    from pg_policies where schemaname = 'public'
  ) x) as policies,
  (select coalesce(json_agg(row_to_json(x)), '[]'::json) from (
    select table_name, grantee, privilege_type
    from information_schema.role_table_grants
    where table_schema = 'public'
      and grantee in ('anon', 'authenticated', 'service_role', 'public')
  ) x) as grants;
`

function sh(cmd, args) {
  return execFileSync(cmd, args, { encoding: "utf8", maxBuffer: 64 * 1024 * 1024, shell: process.platform === "win32" })
}

// CATALOG_SQL is executed through `supabase db query --linked --file` because
// --file is the only supported non-interactive input on Windows.
const sqlPath = process.env.STAGING_BASE_SQL ?? "staging-base-catalog.sql"
writeFileSync(sqlPath, CATALOG_SQL)
const raw = sh("npx", ["supabase", "db", "query", "--linked", "--output", "json", "--file", sqlPath])
const start = raw.indexOf("[")
if (start < 0) throw new Error("no JSON output from db query")
const cat = JSON.parse(raw.slice(start))[0]

const out = []
out.push("-- Base schema reconstructed from production catalog (metadata only).")
out.push("-- Generated for staging seeding; review before applying.")
out.push("")

const quoted = (id) => `"${id.replace(/"/g, '""')}"`

// --- SECTION: TABLES
const colsByTable = new Map()
for (const c of cat.columns) {
  if (!colsByTable.has(c.tbl)) colsByTable.set(c.tbl, [])
  colsByTable.get(c.tbl).push(c)
}
out.push("-- SECTION: TABLES")
for (const t of cat.tables) {
  const cols = colsByTable.get(t.table_name) ?? []
  const lines = cols.map((c) => {
    let line = `  ${quoted(c.col)} ${c.typ}`
    if (c.ident === "a") line += " GENERATED ALWAYS AS IDENTITY"
    if (c.ident === "d") line += " GENERATED BY DEFAULT AS IDENTITY"
    if (c.deflt !== null) line += ` DEFAULT ${c.deflt}`
    if (c.notnull) line += " NOT NULL"
    return line
  })
  out.push(`create table public.${quoted(t.table_name)} (`)
  out.push(lines.join(",\n"))
  out.push(");")
  if (t.rls) out.push(`alter table public.${quoted(t.table_name)} enable row level security;`)
  out.push("")
}

// --- SECTION: CONSTRAINTS (PK/UNIQUE first: FKs reference their indexes;
// CHECK last so column expressions reference settled tables)
out.push("-- SECTION: CONSTRAINTS")
const order = { p: 0, u: 1, f: 2, c: 3 }
for (const k of [...cat.constraints].sort((a, b) => (order[a.contype] ?? 9) - (order[b.contype] ?? 9))) {
  const tbl = k.tbl.replace(/^public\./, "")
  out.push(
    `alter table public.${quoted(tbl)} add constraint ${quoted(k.conname)} ${k.def};`,
  )
}
out.push("")

// --- SECTION: INDEXES (constraint-backed ones excluded)
out.push("-- SECTION: INDEXES")
const constraintNames = new Set(cat.constraints.map((k) => k.conname))
for (const i of cat.indexes) {
  if (constraintNames.has(i.indexname)) continue
  out.push(i.indexdef + ";")
}
out.push("")

// --- SECTION: FUNCTIONS (all app schemas incl. private)
out.push("-- SECTION: FUNCTIONS")
const seenSchemas = new Set()
for (const f of cat.functions) {
  if (!seenSchemas.has(f.schema_name)) {
    seenSchemas.add(f.schema_name)
    if (f.schema_name !== "public") {
      out.push(`create schema if not exists ${quoted(f.schema_name)};`)
      out.push("")
    }
  }
  out.push(f.def.replace(/;?\s*$/, ";"))
  out.push("")
}

// --- SECTION: TRIGGERS
out.push("-- SECTION: TRIGGERS")
for (const t of cat.triggers) {
  out.push(t.def + ";")
}
out.push("")

// --- SECTION: POLICIES
out.push("-- SECTION: POLICIES")
for (const p of cat.policies) {
  const roles = (p.roles ?? []).join(", ")
  const parts = [
    `create policy ${JSON.stringify(p.policyname)}`,
    `on public.${quoted(p.tablename)}`,
    `as ${p.permissive}`,
    `for ${p.cmd}`,
    `to ${roles}`,
  ]
  if (p.qual) parts.push(`using (${p.qual})`)
  if (p.with_check) parts.push(`with check (${p.with_check})`)
  out.push(parts.join("\n  ") + ";")
}
out.push("")

// --- SECTION: GRANTS (aggregated per table/grantee)
out.push("-- SECTION: GRANTS")
const grantMap = new Map()
for (const g of cat.grants) {
  const key = `${g.table_name}|${g.grantee}`
  if (!grantMap.has(key)) grantMap.set(key, new Set())
  grantMap.get(key).add(g.privilege_type)
}
for (const [key, privs] of grantMap) {
  const [tbl, grantee] = key.split("|")
  const privList = privs.has("ALL") ? ["ALL"] : [...privs].sort()
  out.push(
    `grant ${privList.join(", ")} on public.${quoted(tbl)} to ${grantee === "public" ? "public" : quoted(grantee)};`,
  )
}

const outPath = process.env.STAGING_BASE_OUT ?? "staging-base.sql"
writeFileSync(outPath, out.join("\n"))
console.log(
  `generated: ${cat.tables.length} tables, ${cat.constraints.length} constraints, ${cat.indexes.length} indexes, ${cat.functions.length} functions, ${cat.triggers.length} triggers, ${cat.policies.length} policies, ${grantMap.size} grants`,
)
